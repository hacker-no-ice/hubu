#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BENCH_ADDR="${HUBU_BENCH_ADDR:-127.0.0.1:8790}"
BENCH_URL="http://${BENCH_ADDR}"
DB_PATH="${HUBU_BENCH_DB_PATH:-$(mktemp -t hubu-bench.XXXXXX.sqlite3)}"
REPORT_DIR="${HUBU_BENCH_REPORT_DIR:-${ROOT_DIR}/target/hubu-bench}"
REPORT_FILE="${REPORT_DIR}/mvp-performance-report.md"
BENCH_LOG="${REPORT_DIR}/benchmark-output.txt"
STATS_LOG="${REPORT_DIR}/system-stats.tsv"
SERVER_LOG="${REPORT_DIR}/server.log"
AGENTS="${HUBU_BENCH_AGENTS:-4}"
RPS="${HUBU_BENCH_RPS:-8}"
DURATION="${HUBU_BENCH_DURATION_SECONDS:-10}"
WORKERS="${HUBU_BENCH_WORKERS:-4}"
SERVER_PID=""
MONITOR_PID=""

cleanup() {
  if [[ -n "${MONITOR_PID}" ]] && kill -0 "${MONITOR_PID}" >/dev/null 2>&1; then
    kill "${MONITOR_PID}" >/dev/null 2>&1 || true
    wait "${MONITOR_PID}" >/dev/null 2>&1 || true
  fi
  if [[ -n "${SERVER_PID}" ]] && kill -0 "${SERVER_PID}" >/dev/null 2>&1; then
    kill "${SERVER_PID}" >/dev/null 2>&1 || true
    wait "${SERVER_PID}" >/dev/null 2>&1 || true
  fi
}
trap cleanup EXIT

sample_stats() {
  printf 'epoch\tserver_cpu_percent\tserver_mem_percent\tserver_rss_kb\tload_1m\tload_5m\tload_15m\n' >"${STATS_LOG}"
  while true; do
    local ps_line load_line
    ps_line="$(ps -p "${SERVER_PID}" -o %cpu=,%mem=,rss= 2>/dev/null || true)"
    load_line="$(uptime | sed 's/^.*load averages*: //')"
    if [[ -z "${ps_line}" ]]; then
      break
    fi
    # shellcheck disable=SC2086
    set -- ${ps_line}
    printf '%s\t%s\t%s\t%s\t%s\n' "$(date +%s)" "$1" "$2" "$3" "${load_line//,/$'\t'}" >>"${STATS_LOG}"
    sleep 1
  done
}

mkdir -p "${REPORT_DIR}"

cd "${ROOT_DIR}"
printf 'Building benchmark binaries...\n'
cargo build --bin hubu-server --bin hubu-bench --bin hubu

printf 'Starting Hubu server at %s...\n' "${BENCH_URL}"
HUBU_DB_PATH="${DB_PATH}" HUBU_LOG_FILE="${SERVER_LOG}" HUBU_LOG_STDERR=0 "${ROOT_DIR}/target/debug/hubu-server" "${BENCH_ADDR}" >"${SERVER_LOG}" 2>&1 &
SERVER_PID="$!"
sleep 0.2

printf 'Waiting for server readiness...\n'
server_ready=""
for _ in $(seq 1 100); do
  if [[ -n "${SERVER_PID}" ]] && ! kill -0 "${SERVER_PID}" >/dev/null 2>&1; then
    sed 's/^/  /' "${SERVER_LOG}" >&2 || true
    exit 1
  fi
  if "${ROOT_DIR}/target/debug/hubu" --url "${BENCH_URL}" health >/dev/null 2>&1; then
    server_ready="yes"
    break
  fi
  sleep 0.1
done
if [[ -z "${server_ready}" ]]; then
  sed 's/^/  /' "${SERVER_LOG}" >&2 || true
  exit 1
fi

sample_stats &
MONITOR_PID="$!"

printf 'Running benchmark: agents=%s rps=%s duration=%ss workers=%s\n' "${AGENTS}" "${RPS}" "${DURATION}" "${WORKERS}"
"${ROOT_DIR}/target/debug/hubu-bench" \
  --url "${BENCH_URL}" \
  --agents "${AGENTS}" \
  --rps "${RPS}" \
  --duration-seconds "${DURATION}" \
  --workers "${WORKERS}" \
  --max-error-rate 0.00 \
  >"${BENCH_LOG}"

sleep 1

avg_cpu="$(awk 'NR > 1 { sum += $2; count += 1 } END { if (count) printf "%.2f", sum / count; else printf "0.00" }' "${STATS_LOG}")"
max_cpu="$(awk 'NR > 1 { if ($2 > max) max = $2 } END { printf "%.2f", max }' "${STATS_LOG}")"
max_rss="$(awk 'NR > 1 { if ($4 > max) max = $4 } END { printf "%d", max }' "${STATS_LOG}")"
achieved_rps="$(awk '/  achieved_rps:/ { print $2 }' "${BENCH_LOG}")"
p95_ms="$(awk '/  latency_p95_ms:/ { print $2 }' "${BENCH_LOG}")"
p99_ms="$(awk '/  latency_p99_ms:/ { print $2 }' "${BENCH_LOG}")"
requests="$(awk '/  requests:/ { print $2 }' "${BENCH_LOG}")"
errors="$(awk '/  errors:/ { print $2 }' "${BENCH_LOG}")"
correct="$(awk '/  correct:/ { print $2 }' "${BENCH_LOG}")"
ledger_transactions="$(awk '/  ledger_transactions:/ { print $2 }' "${BENCH_LOG}")"

cat >"${REPORT_FILE}" <<EOF
# Hubu MVP Local Performance, Scalability, and Reliability Report

Generated by \`scripts/benchmark-local.sh\`.

> **Experimental local benchmark.** This report covers a localhost demo server
> using a broad local bearer capability and mock payment rail. Its metrics are
> not a capacity claim, service-level objective, production load test, or
> security test, and must not be used to approve real-money production use.

## Scenario

- One local Hubu server process
- One owner user
- ${AGENTS} registered agents
- ${RPS} target spend approval requests/sec for ${DURATION} seconds
- ${WORKERS} client worker threads
- Request path: HTTP \`POST /spend\` through policy evaluation, auth token issuance, budget reservation, mock payment, budget settlement, and ledger recording

## Performance Metrics

- Requests completed: ${requests}
- Achieved throughput: ${achieved_rps} requests/sec
- p95 latency: ${p95_ms} ms
- p99 latency: ${p99_ms} ms
- Server average CPU: ${avg_cpu}%
- Server peak CPU: ${max_cpu}%
- Server peak RSS: ${max_rss} KB

## Correctness Metrics

- Correctness checks passed: ${correct}
- Request errors: ${errors}
- Ledger transactions: ${ledger_transactions}

Full benchmark output: \`${BENCH_LOG}\`

System stats log: \`${STATS_LOG}\`

Server log: \`${SERVER_LOG}\`

## Scalability Assessment

This MVP server is intentionally simple and handles accepted TCP connections in a single blocking loop. The benchmark therefore measures the complete demo path, but it also highlights that concurrency is serialized before route handling. Higher request rates will queue at the client/server socket layer rather than exercising parallel policy, budget, payment, or ledger work.

## Reliability Assessment

The benchmark verifies that allowed spend decisions receive auth tokens, successful payments settle budget holds, failed payments release holds, the ledger transaction count matches successful payments, and no budget remains frozen after the run. A passing run means the MVP path stayed internally consistent under the selected local load.

## Top Things To Address

1. Replace the blocking one-connection-at-a-time local server with a concurrent HTTP runtime.
2. Move shared state from coarse \`Mutex\` guards to storage and synchronization boundaries that match the domain invariants, especially spend tokens, budget holds, and ledger writes.
3. Extend the load benchmark with duplicate operation keys and restart injection to exercise the existing idempotency tests under concurrency.
4. Add first-class telemetry: structured request logs, latency histograms, error counters, and budget/ledger consistency gauges.
5. Extend this benchmark with mixed allow/deny/needs-approval/payment-failure scenarios and a step-load mode to find saturation points safely.
EOF

printf 'Report written to %s\n' "${REPORT_FILE}"
